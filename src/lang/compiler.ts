import { check } from './checker';
import { LanguageError, type Expr, type Program } from './types';
/** Emits JavaScript, never evaluates it. Supply the small Sourced runtime as `rt`. */
export function compile(program: Program): string {
  const issue = program.diagnostics[0] ?? check(program)[0];
  if (issue) throw new LanguageError(issue);
  const names = new Map<string, string>();
  const functions = new Map<string, string>();
  let serial = 0;
  const span = (at: { start: number; end: number }) =>
    JSON.stringify({ start: at.start, end: at.end });
  const expression = (expr: Expr, scope: Map<string, string>, assumption?: string): string => {
    const at = span(expr);
    switch (expr.kind) {
      case 'number':
        return `rt.number(${expr.value}, ${JSON.stringify(expr.unit)}, ${JSON.stringify(expr.source) ?? 'undefined'}, ${JSON.stringify(assumption) ?? 'undefined'}, ${at}${expr.uncertainty ? `, ${JSON.stringify(expr.uncertainty)}` : ''})`;
      case 'name':
        return scope.get(expr.name) ?? 'undefined';
      case 'list':
        return `[${expr.items.map((item) => expression(item, scope, assumption)).join(', ')}]`;
      case 'unary':
        return `rt.unary(${JSON.stringify(expr.op)}, ${expression(expr.value, scope, assumption)}, ${at})`;
      case 'binary':
        return `rt.binary(${JSON.stringify(expr.op)}, ${expression(expr.left, scope, assumption)}, ${expression(expr.right, scope, assumption)}, ${at})`;
      case 'convert':
        return `rt.convert(${expression(expr.value, scope, assumption)}, ${JSON.stringify(expr.unit)}, ${at})`;
      case 'call': {
        const args = expr.args.map((arg) => expression(arg, scope, assumption)).join(', ');
        return ['sum', 'round', 'sqrt'].includes(expr.name)
          ? `rt.builtin(${JSON.stringify(expr.name)}, [${args}], ${at})`
          : `${functions.get(expr.name)}(${args})`;
      }
    }
  };
  const lines = ['"use strict";', '// Generated by Sourced. Runtime is provided as rt.'];
  for (const statement of program.statements) {
    if (statement.kind === 'source') lines.push(`rt.source(${JSON.stringify(statement)});`);
    if (statement.kind === 'binding') {
      const value = expression(
        statement.value,
        names,
        statement.assume ? statement.name : undefined,
      );
      const name = `v${serial++}`;
      names.set(statement.name, name);
      lines.push(
        `const ${name} = rt.bind(${JSON.stringify(statement.name)}, ${value}, ${statement.assume}, ${span(statement)});`,
      );
    }
    if (statement.kind === 'function') {
      const scope = new Map(names);
      const params = statement.params.map((param) => {
        const name = `p${serial++}`;
        scope.set(param, name);
        return name;
      });
      const name = `f${serial++}`;
      lines.push(`const ${name} = (${params.join(', ')}) => ${expression(statement.body, scope)};`);
      functions.set(statement.name, name);
    }
    if (statement.kind === 'print')
      lines.push(
        `rt.print([${statement.parts.map((part) => ('text' in part ? JSON.stringify(part.text) : expression(part.expr, names))).join(', ')}], ${span(statement)});`,
      );
  }
  lines.push('return rt.result();');
  return lines.join('\n');
}
